// Задание 2: RAM[108] = RAM[RAM[16] + 16] * RAM[RAM[16] - 16] + 2

// 1. Получаем первый множитель: RAM[RAM[16] + 16] -> сохраняем в R13
@16
D=M
@16
A=D+A       // A = RAM[16] + 16
D=M         // D = RAM[RAM[16] + 16]
@R13
M=D

// 2. Получаем второй множитель: RAM[RAM[16] - 16] -> сохраняем в R14
@16
D=M
@16
A=D-A       // A = RAM[16] - 16
D=M         // D = RAM[RAM[16] - 16]
@R14
M=D

// 3. Умножаем R13 * R14 (результат накапливаем в R15)
@R15
M=0

(MULT_LOOP)
    // Проверяем счетчик R14: если R14 == 0, выходим из цикла
    @R14
    D=M
    @MULT_END
    D;JEQ

    // R15 = R15 + R13
    @R13
    D=M
    @R15
    M=D+M

    // R14 = R14 - 1
    @R14
    M=M-1

    @MULT_LOOP
    0;JMP

(MULT_END)
// 4. Прибавляем 2 и записываем в RAM[108]
@R15
D=M
@2
D=D+A
@108
M=D

(END)
@END
0;JMP
